/**
 * Enemy & boss definitions. Behaviour is data-driven: each enemy has a movement
 * style and a list of telegraphed attacks that the generic AI chooses from.
 */
import type { ProjectileId, SpriteId } from '../art/pixel/types';
import type { MaterialId } from '../game/types';

export type StatusKind = 'burn' | 'poison' | 'slow' | 'freeze';

export interface StatusSpec {
  kind: StatusKind;
  duration: number;
  /** DoT: fraction of attacker power per second. Slow: speed reduction fraction. */
  power?: number;
  chance?: number;
}

export interface ProjectileSpec {
  sprite: ProjectileId;
  speed: number;
  radius: number;
  dmg: number;
  life?: number;
  /** Radians per second of turning toward the target. */
  homing?: number;
  status?: StatusSpec;
  /** Explodes on impact / expiry. */
  explode?: { radius: number; dmg: number; status?: StatusSpec };
  /** Size multiplier for drawing. */
  scale?: number;
  /** Leaves a burning / freezing puddle on expiry. */
  puddle?: { radius: number; duration: number; dmg: number; status?: StatusSpec };
}

interface AttackBase {
  /** Seconds of telegraph before the attack fires. */
  windup: number;
  /** Seconds of vulnerability after. */
  recover: number;
  cooldown: number;
  /** Max distance to the player to consider this attack. */
  range: number;
  minRange?: number;
  weight?: number;
  /** Damage multiplier of the enemy's attack stat. */
  dmg: number;
  /** Boss phase (0-based) required to use this attack. */
  phase?: number;
  /** Stop using once the boss reaches this phase. */
  maxPhase?: number;
  status?: StatusSpec;
  sfx?: import('../audio').SfxId;
  /** Shout text shown when used (bosses). */
  shout?: string;
}

export type AttackDef = AttackBase &
  (
    | { type: 'melee'; arc: number; reach: number; repeat?: number }
    | { type: 'lunge'; speed: number; duration: number; repeat?: number }
    | { type: 'charge'; speed: number; length: number }
    | {
        type: 'shoot';
        proj: ProjectileSpec;
        count: number;
        spread: number;
        bursts?: number;
        burstDelay?: number;
        aimJitter?: number;
      }
    | {
        type: 'ring';
        proj: ProjectileSpec;
        count: number;
        waves?: number;
        waveDelay?: number;
        rotate?: number;
      }
    | { type: 'spiral'; proj: ProjectileSpec; arms: number; shots: number; interval: number; turn: number }
    | { type: 'nova'; radius: number; selfDestruct?: boolean }
    | {
        type: 'aoe';
        at: 'player' | 'around' | 'line' | 'cross';
        radius: number;
        count: number;
        spread: number;
        delay: number;
        stagger?: number;
        persist?: number;
      }
    | { type: 'line'; length: number; width: number; persist?: number }
    | { type: 'cone'; length: number; arc: number; duration: number; sweep?: number }
    | { type: 'beam'; length: number; width: number; duration: number; sweep: number }
    | { type: 'summon'; enemy: string; count: number; max: number }
    | { type: 'teleport'; near: 'player' | 'random'; novaRadius?: number }
    | { type: 'dive'; radius: number; airTime: number }
  );

export type Behavior = 'melee' | 'ranged' | 'hopper' | 'flyer' | 'caster' | 'kamikaze' | 'turret' | 'boss';

export interface EnemyDef {
  id: string;
  name: string;
  sprite: SpriteId;
  hp: number;
  atk: number;
  def: number;
  speed: number;
  radius: number;
  /** Knockback resistance 0..1. */
  mass: number;
  xp: number;
  gold: number;
  behavior: Behavior;
  attacks: AttackDef[];
  aggro: number;
  flying?: boolean;
  scale?: number;
  /** Damage reduction when hit from the front while not attacking. */
  guard?: number;
  onDeath?: {
    split?: { enemy: string; count: number };
    explode?: { radius: number; dmg: number; status?: StatusSpec };
  };
  drops?: { material: MaterialId; chance: number }[];
  element?: 'fire' | 'ice' | 'void' | 'nature' | 'earth';
  immune?: StatusKind[];
  lore: string;
  /** Preferred distance for ranged/caster behaviours. */
  keepAway?: number;
  /** Bosses only. */
  boss?: BossInfo;
}

export interface BossPhase {
  /** Enter this phase at or below this HP fraction. */
  at: number;
  speedMult: number;
  cooldownMult: number;
  shout?: string;
  summon?: { enemy: string; count: number };
}

export interface BossInfo {
  title: string;
  phases: BossPhase[];
  music: import('../audio').MusicId;
  /** Portrait for the VS splash (humanoid bosses). */
  portrait?: import('../art/anime').PortraitId;
  shardName?: string;
}

