/** Anime cutscene scripts. Lines use "speaker|expression: text"; {hero} = the hero's name. */
import type { CutInId, IllustrationId } from '../art/anime';
import type { MusicId, SfxId } from '../audio';

export type CutStep =
  | { music: MusicId | null }
  | { illus: IllustrationId | null; fade?: number }
  /** Seek the current illustration's clock (and optionally freeze it). */
  | { illusT: number; freeze?: boolean }
  /** Keep the illustration animating inside [from, to] (e.g. an aura building up) until changed. */
  | { illusLoop: [number, number] | null }
  | { say: string }
  | { narrate: string }
  | { wait: number }
  | { flash: string; dur?: number }
  | { shake: number; dur?: number }
  | { sfx: SfxId }
  | { fadeOut: number; color?: string }
  | { fadeIn: number }
  | { title: string; sub?: string; dur?: number }
  | { cutin: CutInId }
  | { speedlines: boolean }
  /** Manga impact frame: two-tone inverted strobe for `impact` seconds (doesn't wait). */
  | { impact: number; style?: 'dark' | 'light' | 'red' | 'cyan' }
  /** Quick zoom punch toward (x, y) as fractions of the screen (doesn't wait). */
  | { zoom: number; x?: number; y?: number; dur?: number };

